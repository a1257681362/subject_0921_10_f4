-- H2 本地文件数据库初始化脚本。
-- base-0：EVOPS 初始工作区
-- exam-1：考试机构考场与准考证建档工作区（报名 / 编排 / 发证 / 查档）
-- grade-1：出分等级与成绩复核（卷面分按段定级，规则带版本；批次复核窗口、复核闭环与改分留痕）
-- mix-1：同校混编整改（名册学校信息；混编算法模块/版本/状态；按比例摊考场 + 种子座次；重排与同校相邻统计；座次表导出）

CREATE TABLE IF NOT EXISTS t_evops_schema_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_no VARCHAR(32) NOT NULL,
    description VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_evops_schema_version UNIQUE (version_no)
);

-- ============ 考点 ============
CREATE TABLE IF NOT EXISTS t_exam_site (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(32) NOT NULL,
    name VARCHAR(128) NOT NULL,
    address VARCHAR(255),
    contact_person VARCHAR(64),
    contact_phone VARCHAR(32),
    status VARCHAR(16) NOT NULL DEFAULT 'ENABLED',
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_exam_site_code UNIQUE (code)
);

-- ============ 考场（归属考点，容量、位置记全） ============
CREATE TABLE IF NOT EXISTS t_exam_room (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id BIGINT NOT NULL,
    room_no VARCHAR(32) NOT NULL,
    building VARCHAR(64),
    floor_no INT,
    capacity INT NOT NULL,
    location_desc VARCHAR(255),
    status VARCHAR(16) NOT NULL DEFAULT 'ENABLED',
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_exam_room_site_no UNIQUE (site_id, room_no),
    CONSTRAINT ck_exam_room_capacity CHECK (capacity > 0)
);

-- ============ 考试批次 ============
CREATE TABLE IF NOT EXISTS t_exam_batch (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(32) NOT NULL,
    name VARCHAR(128) NOT NULL,
    site_id BIGINT NOT NULL,
    subject VARCHAR(128),
    -- 项目编码：等级规则与复核窗口按项目串起来（本批次先跑 ZHUKAO 助考）
    project_code VARCHAR(32) NOT NULL DEFAULT 'DEFAULT',
    exam_date DATE,
    start_time TIME,
    end_time TIME,
    -- 成绩复核窗口起止：跟批次配置走，不写死；为空表示未配置窗口
    review_start_at TIMESTAMP,
    review_end_at TIMESTAMP,
    -- CREATED 建档 / ARRANGED 已编排 / FINALIZED 已办结
    status VARCHAR(16) NOT NULL DEFAULT 'CREATED',
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_exam_batch_code UNIQUE (code)
);
-- 老库平滑加列（H2 2.x 支持 IF NOT EXISTS；新库由 CREATE TABLE 带列，这两句跳过）
ALTER TABLE t_exam_batch ADD COLUMN IF NOT EXISTS project_code VARCHAR(32) NOT NULL DEFAULT 'DEFAULT';
ALTER TABLE t_exam_batch ADD COLUMN IF NOT EXISTS review_start_at TIMESTAMP;
ALTER TABLE t_exam_batch ADD COLUMN IF NOT EXISTS review_end_at TIMESTAMP;

-- ============ 报名名册 ============
CREATE TABLE IF NOT EXISTS t_registration (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reg_no VARCHAR(40) NOT NULL,
    name VARCHAR(64) NOT NULL,
    id_type VARCHAR(16) NOT NULL DEFAULT 'ID_CARD',
    id_no VARCHAR(32),
    gender VARCHAR(8),
    phone VARCHAR(32),
    batch_id BIGINT NOT NULL,
    subject VARCHAR(128),
    -- 所属学校（机构）：同校学员混排错开的分组依据；为空表示未知学校，不参与同校相邻判定
    school VARCHAR(128),
    -- REGISTERED 已报名 / ARRANGED 已编排
    status VARCHAR(16) NOT NULL DEFAULT 'REGISTERED',
    correction_count INT NOT NULL DEFAULT 0,
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_registration_reg_no UNIQUE (reg_no)
);
-- 老库平滑加列（H2 2.x 支持 IF NOT EXISTS；新库由 CREATE TABLE 带列，此句跳过）；必须先加列再建索引
ALTER TABLE t_registration ADD COLUMN IF NOT EXISTS school VARCHAR(128);
CREATE INDEX IF NOT EXISTS idx_registration_name ON t_registration (name);
CREATE INDEX IF NOT EXISTS idx_registration_batch ON t_registration (batch_id);
CREATE INDEX IF NOT EXISTS idx_registration_school ON t_registration (school);

-- ============ 名册勘误（只追加，旧值留痕，不覆盖历史） ============
CREATE TABLE IF NOT EXISTS t_registration_correction (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration_id BIGINT NOT NULL,
    field_name VARCHAR(32) NOT NULL,
    field_label VARCHAR(64),
    old_value VARCHAR(255),
    new_value VARCHAR(255),
    reason VARCHAR(255),
    operator VARCHAR(64),
    corrected_at TIMESTAMP NOT NULL,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_correction_reg ON t_registration_correction (registration_id);

-- ============ 准考证（证号全局唯一；批次内考场+座位唯一） ============
CREATE TABLE IF NOT EXISTS t_admission_ticket (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_no VARCHAR(40) NOT NULL,
    registration_id BIGINT NOT NULL,
    batch_id BIGINT NOT NULL,
    site_id BIGINT NOT NULL,
    room_id BIGINT NOT NULL,
    seat_no INT NOT NULL,
    -- PENDING 待打印 / PRINTED 已打印 / ISSUED 已发放
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    printed_by VARCHAR(64),
    printed_at TIMESTAMP,
    issued_by VARCHAR(64),
    issued_at TIMESTAMP,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_ticket_no UNIQUE (ticket_no),
    CONSTRAINT uk_ticket_registration UNIQUE (registration_id),
    CONSTRAINT uk_ticket_seat UNIQUE (batch_id, room_id, seat_no),
    CONSTRAINT ck_ticket_seat CHECK (seat_no > 0)
);
CREATE INDEX IF NOT EXISTS idx_ticket_batch ON t_admission_ticket (batch_id);

-- ============ 阶段结果（与最终结论分表保存） ============
CREATE TABLE IF NOT EXISTS t_stage_result (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL,
    -- IMPORT 报名导入 / ARRANGEMENT 编排 / PRINTING 打印 / ISSUANCE 发放
    stage VARCHAR(16) NOT NULL,
    affected_count INT NOT NULL DEFAULT 0,
    detail CLOB,
    operator VARCHAR(64),
    executed_at TIMESTAMP NOT NULL,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_stage_batch ON t_stage_result (batch_id);

-- ============ 最终结论 ============
CREATE TABLE IF NOT EXISTS t_final_conclusion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL,
    conclusion_code VARCHAR(32) NOT NULL,
    summary VARCHAR(512),
    total_count INT NOT NULL DEFAULT 0,
    printed_count INT NOT NULL DEFAULT 0,
    issued_count INT NOT NULL DEFAULT 0,
    operator VARCHAR(64),
    concluded_at TIMESTAMP NOT NULL,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_final_conclusion_batch UNIQUE (batch_id)
);

-- ============ 工作区版本（版本选择 / 状态回退可追溯） ============
CREATE TABLE IF NOT EXISTS t_workspace_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_no VARCHAR(40) NOT NULL,
    label VARCHAR(128) NOT NULL,
    -- SNAPSHOT 快照 / ROLLBACK 回退生成
    kind VARCHAR(16) NOT NULL DEFAULT 'SNAPSHOT',
    restored_from_version VARCHAR(40),
    -- 同一时刻只有一个当前版本
    is_current BOOLEAN NOT NULL DEFAULT FALSE,
    snapshot CLOB,
    remark VARCHAR(255),
    operator VARCHAR(64),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_workspace_version_no UNIQUE (version_no)
);

-- 工作区版本事件（CREATE/SELECT/ROLLBACK 全程留痕；回退不清此表）
CREATE TABLE IF NOT EXISTS t_workspace_version_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id BIGINT NOT NULL,
    version_no VARCHAR(40) NOT NULL,
    action VARCHAR(16) NOT NULL,
    detail VARCHAR(512),
    operator VARCHAR(64),
    event_at TIMESTAMP NOT NULL,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_version_event_version ON t_workspace_version_event (version_id);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('base-0', 'EVOPS 初始工作区');

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('exam-1', '考试机构考场与准考证建档工作区：报名、编排、发证、查档');

-- ============ 等级规则模块（一个项目一套规则，规则下挂多个版本） ============
CREATE TABLE IF NOT EXISTS t_grade_rule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(32) NOT NULL,
    name VARCHAR(128) NOT NULL,
    -- 项目编码：与批次 project_code 对齐（助考等项目各管各的口径）
    project_code VARCHAR(32) NOT NULL,
    subject VARCHAR(128),
    -- 满分（各分数段须落在 [0, max_score]）
    max_score INT NOT NULL DEFAULT 100,
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_grade_rule_code UNIQUE (code),
    CONSTRAINT ck_grade_rule_max CHECK (max_score > 0)
);

-- ============ 等级规则版本（卷面分按分数段落等级；发布后冻结，永不修改） ============
CREATE TABLE IF NOT EXISTS t_grade_rule_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_id BIGINT NOT NULL,
    version_no VARCHAR(40) NOT NULL,
    -- DRAFT 草稿 / ACTIVE 生效（同一规则同时刻仅一版；同项目可按科目各有一条规则） / DISABLED 停用
    status VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
    -- 分数段定义（发布时冻结的 JSON）：[{"minScore":0,"maxScore":60,"grade":"不合格"},...]
    -- 约定左闭右开 [minScore,maxScore)，段段相连不重叠不缺口，末段右端 = 满分
    grade_bands CLOB NOT NULL,
    remark VARCHAR(255),
    published_by VARCHAR(64),
    published_at TIMESTAMP,
    disabled_by VARCHAR(64),
    disabled_at TIMESTAMP,
    operator VARCHAR(64),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_grade_rule_version_no UNIQUE (version_no)
);
CREATE INDEX IF NOT EXISTS idx_grade_version_rule ON t_grade_rule_version (rule_id);
CREATE INDEX IF NOT EXISTS idx_grade_version_project_status ON t_grade_rule_version (status);

-- ============ 成绩（一人一批次一条；定级时记下规则版本，口径可追溯） ============
CREATE TABLE IF NOT EXISTS t_exam_score (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL,
    registration_id BIGINT NOT NULL,
    reg_no VARCHAR(40) NOT NULL,
    name VARCHAR(64) NOT NULL,
    paper_score DECIMAL(6,2) NOT NULL,
    final_score DECIMAL(6,2),
    grade VARCHAR(16),
    -- 定级所用规则版本快照外键与版本号；规则版本停用/升级不影响历史口径
    rule_version_id BIGINT,
    rule_version_no VARCHAR(40),
    graded_at TIMESTAMP,
    -- RECORDED 已录入 / REVIEWING 复核中
    status VARCHAR(16) NOT NULL DEFAULT 'RECORDED',
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_score_registration UNIQUE (registration_id),
    CONSTRAINT ck_score_paper CHECK (paper_score >= 0)
);
CREATE INDEX IF NOT EXISTS idx_score_batch ON t_exam_score (batch_id);
CREATE INDEX IF NOT EXISTS idx_score_reg_no ON t_exam_score (reg_no);

-- ============ 成绩复核申请（窗口跟批次配置；超窗由定时任务自动关闭） ============
CREATE TABLE IF NOT EXISTS t_score_review (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    score_id BIGINT NOT NULL,
    batch_id BIGINT NOT NULL,
    registration_id BIGINT NOT NULL,
    reg_no VARCHAR(40) NOT NULL,
    name VARCHAR(64) NOT NULL,
    apply_reason VARCHAR(512),
    applicant VARCHAR(64),
    applied_at TIMESTAMP NOT NULL,
    -- SUBMITTED 待处理 / APPROVED 复核通过（改分） / REJECTED 复核驳回 / CLOSED 超窗自动关闭
    status VARCHAR(16) NOT NULL DEFAULT 'SUBMITTED',
    conclusion VARCHAR(512),
    reviewer VARCHAR(64),
    concluded_at TIMESTAMP,
    -- 结论时的改分前后快照，与改分日志互为印证
    score_before DECIMAL(6,2),
    grade_before VARCHAR(16),
    score_after DECIMAL(6,2),
    grade_after VARCHAR(16),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_review_batch ON t_score_review (batch_id);
CREATE INDEX IF NOT EXISTS idx_review_score ON t_score_review (score_id);
CREATE INDEX IF NOT EXISTS idx_review_status ON t_score_review (status);

-- ============ 改分留痕（改分前后都留痕，只追加） ============
CREATE TABLE IF NOT EXISTS t_score_change_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    score_id BIGINT NOT NULL,
    review_id BIGINT,
    batch_id BIGINT NOT NULL,
    reg_no VARCHAR(40) NOT NULL,
    name VARCHAR(64) NOT NULL,
    score_before DECIMAL(6,2) NOT NULL,
    score_after DECIMAL(6,2) NOT NULL,
    grade_before VARCHAR(16),
    grade_after VARCHAR(16),
    change_reason VARCHAR(512),
    rule_version_no VARCHAR(40),
    operator VARCHAR(64),
    changed_at TIMESTAMP NOT NULL,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_change_log_score ON t_score_change_log (score_id);
CREATE INDEX IF NOT EXISTS idx_change_log_batch ON t_score_change_log (batch_id);

-- ============ 站内通知（复核结论 / 超窗关闭都通知；本版先落库，外发下版再接） ============
CREATE TABLE IF NOT EXISTS t_score_notification (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT,
    registration_id BIGINT,
    reg_no VARCHAR(40),
    name VARCHAR(64),
    -- REVIEW_RESULT 复核结论 / REVIEW_CLOSED 超窗关闭
    notify_type VARCHAR(24) NOT NULL,
    title VARCHAR(128) NOT NULL,
    content VARCHAR(1024) NOT NULL,
    -- NEW 未读 / READ 已读
    status VARCHAR(16) NOT NULL DEFAULT 'NEW',
    review_id BIGINT,
    operator VARCHAR(64),
    notified_at TIMESTAMP NOT NULL,
    read_at TIMESTAMP,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_notify_reg ON t_score_notification (registration_id);
CREATE INDEX IF NOT EXISTS idx_notify_status ON t_score_notification (status);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
