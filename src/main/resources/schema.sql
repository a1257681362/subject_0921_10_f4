CREATE INDEX IF NOT EXISTS idx_replacement_appt ON t_appointment_replacement (appointment_id);
CREATE INDEX IF NOT EXISTS idx_replacement_batch ON t_appointment_replacement (batch_id);

-- ============ 监考费结算单（按周期一键生成；草稿可重算，确认后锁定） ============
CREATE TABLE IF NOT EXISTS t_settlement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    settlement_no VARCHAR(48) NOT NULL,
    -- 结算周期（按月）：period_start 含、period_end 不含；按聘任场次的签到时间归属周期
    period_start DATE NOT NULL,
    period_end DATE NOT NULL,
    period_label VARCHAR(16) NOT NULL,
    -- DRAFT 草稿（可重复生成/重算） / CONFIRMED 已确认锁定（要改走调整）
    status VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
    total_appointments INT NOT NULL DEFAULT 0,
    total_amount DECIMAL(12,2) NOT NULL DEFAULT 0,
    -- 调整后应付（初值=合计；调整单累加变动额）
    payable_amount DECIMAL(12,2) NOT NULL DEFAULT 0,
    adjust_count INT NOT NULL DEFAULT 0,
    remark VARCHAR(255),
    confirmed_by VARCHAR(64),
    confirmed_at TIMESTAMP,
    operator VARCHAR(64),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_settlement_no UNIQUE (settlement_no)
);
CREATE INDEX IF NOT EXISTS idx_settlement_period ON t_settlement (period_start, period_end);

-- ============ 结算单明细（一人一行：场次与金额；确认后锁定，要改走调整） ============
CREATE TABLE IF NOT EXISTS t_settlement_item (
