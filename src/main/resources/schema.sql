CREATE INDEX IF NOT EXISTS idx_settlement_item_settlement ON t_settlement_item (settlement_id);
CREATE INDEX IF NOT EXISTS idx_settlement_item_person ON t_settlement_item (invigilator_id);

-- ============ 结算调整台账（确认锁定后唯一改动入口；只追加，结算单/明细记累计变动） ============
