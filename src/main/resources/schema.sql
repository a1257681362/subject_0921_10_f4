-- ============ 混编算法模块（同校错开编排的算法定义，可按项目各建一套） ============
CREATE TABLE IF NOT EXISTS t_mix_algorithm (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(32) NOT NULL,
    name VARCHAR(128) NOT NULL,
    -- 项目编码：与批次 project_code 对齐；编排时取项目当前生效算法
    project_code VARCHAR(32) NOT NULL DEFAULT 'DEFAULT',
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_mix_algorithm_code UNIQUE (code)
);

-- ============ 混编算法版本（参数 JSON 发布即冻结；DRAFT/ACTIVE/DISABLED，同模块同时刻仅一版生效） ============
CREATE TABLE IF NOT EXISTS t_mix_algorithm_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    algorithm_id BIGINT NOT NULL,
    version_no VARCHAR(40) NOT NULL,
    -- DRAFT 草稿 / ACTIVE 生效 / DISABLED 停用（被新版本顶替或人工停用）
    status VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
    -- 发布时冻结的算法参数 JSON：
    -- {"strategy":"SCHOOL_SPREAD","minSchoolGap":1,"maxSameSchoolPerRoom":null,"spreadRooms":true,"tries":40}
    -- minSchoolGap 同校学员在同考场内的最小座位间隔；spreadRooms 是否把同校按容量比例摊到多个考场
    params CLOB NOT NULL,
    remark VARCHAR(255),
    published_by VARCHAR(64),
    published_at TIMESTAMP,
    disabled_by VARCHAR(64),
    disabled_at TIMESTAMP,
    operator VARCHAR(64),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_mix_algorithm_version_no UNIQUE (version_no)
);
CREATE INDEX IF NOT EXISTS idx_mix_version_algorithm ON t_mix_algorithm_version (algorithm_id);
CREATE INDEX IF NOT EXISTS idx_mix_version_status ON t_mix_algorithm_version (status);

-- ============ 编排记录（每次编排/整批重排一条：算法版本、随机种子、座次快照、同校相邻统计；只追加） ============
CREATE TABLE IF NOT EXISTS t_arrangement_run (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL,
    -- ARRANGE 首次编排 / REARRANGE 整批重排
    run_type VARCHAR(16) NOT NULL,
    -- 本次使用的混编算法版本（算法/版本可追溯；无算法版本时为空，按顺序编排）
    mix_version_id BIGINT,
    mix_version_no VARCHAR(40),
    -- 洗牌随机种子：同种子同名册同考场可复现座次
    seed BIGINT NOT NULL,
    -- 座次快照 JSON：[{ticketNo,regNo,name,school,roomId,roomNo,seatNo},...]
    seating CLOB NOT NULL,
    total_count INT NOT NULL DEFAULT 0,
    room_count INT NOT NULL DEFAULT 0,
    -- 同校相邻对数（相邻=同考场座位号连续）；巡考抽查口径
    same_school_adjacent_count INT NOT NULL DEFAULT 0,
    -- 同校相邻明细 JSON：[{roomNo,seatA,seatB,school,nameA,nameB},...]
    adjacent_detail CLOB,
    -- 同批次同时刻仅一条当前编排；重排只切当前标记，旧记录保留
    is_current BOOLEAN NOT NULL DEFAULT FALSE,
    operator VARCHAR(64),
    executed_at TIMESTAMP NOT NULL,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_arrangement_run_batch ON t_arrangement_run (batch_id);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('mix-1', '同校混编整改：名册学校信息、混编算法模块/版本/状态、按比例摊考场与种子座次、整批重排、同校相邻统计、座次表导出');

-- ==========================================================================
-- staff-1：兼职监考聘任与结算
-- 监考随排班（编排）生成聘任；场次结束签到后按角色标准计津贴；
-- 换人走 REPLACE 版本留痕；缺勤标记后不计费、冲销已计；
-- 月底一键出结算单（人事全量 / 本人只看自己），确认锁定，要改走调整单。
-- ==========================================================================

-- ============ 监考人员（兼职老师花名册；工号全局唯一） ============
CREATE TABLE IF NOT EXISTS t_invigilator (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    staff_no VARCHAR(40) NOT NULL,
    name VARCHAR(64) NOT NULL,
    phone VARCHAR(32),
    id_no VARCHAR(32),
    -- 所在单位 / 学校（兼职老师来源单位，仅记录用）
    organization VARCHAR(128),
    -- 可担任角色清单 JSON：["CHIEF_INVIGILATOR","INVIGILATOR","PATROL"]
    -- 角色不同津贴标准不同；排班分配角色时校验是否在其可担任清单内
    available_roles CLOB,
    -- ENABLED 可排班 / DISABLED 停用（历史聘任保留）
    status VARCHAR(16) NOT NULL DEFAULT 'ENABLED',
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_invigilator_staff_no UNIQUE (staff_no)
);
CREATE INDEX IF NOT EXISTS idx_invigilator_name ON t_invigilator (name);

-- ============ 角色定义与单位场次津贴标准（模块；按项目+角色建档，标准挂版本） ============
CREATE TABLE IF NOT EXISTS t_invigilator_stipend (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(32) NOT NULL,
    name VARCHAR(128) NOT NULL,
    -- 项目编码：与批次 project_code 对齐；排班计酬取项目当前生效版
    project_code VARCHAR(32) NOT NULL DEFAULT 'DEFAULT',
    -- 监考角色：CHIEF_INVIGILATOR 主考 / INVIGILATOR 监考员 / PATROL 巡考 / BACKUP 备用
    role_code VARCHAR(32) NOT NULL,
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    -- 同项目同角色仅一套标准模块（角色不同标准不同）
    CONSTRAINT uk_stipend_project_role UNIQUE (project_code, role_code),
    CONSTRAINT uk_stipend_code UNIQUE (code)
);

-- ============ 角色津贴标准版本（DRAFT/ACTIVE/DISABLED，发布即冻结） ============
CREATE TABLE IF NOT EXISTS t_invigilator_stipend_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stipend_id BIGINT NOT NULL,
    version_no VARCHAR(40) NOT NULL,
    -- DRAFT 草稿 / ACTIVE 生效（同模块同时刻仅一版） / DISABLED 停用
    status VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
    -- 单场津贴标准（元）
    rate_per_session DECIMAL(10,2) NOT NULL,
    -- 超场补贴：每多监一场加发金额（可为空表示不设）
    extra_per_session DECIMAL(10,2),
    -- 标准生效起始场次日期（用于说明，实际计酬以聘任时快照为准）
    effective_from DATE,
    -- 发布时冻结的标准说明（可附政策依据）
    remark VARCHAR(255),
    published_by VARCHAR(64),
    published_at TIMESTAMP,
    disabled_by VARCHAR(64),
    disabled_at TIMESTAMP,
    operator VARCHAR(64),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_stipend_version_no UNIQUE (version_no),
    CONSTRAINT ck_stipend_rate CHECK (rate_per_session >= 0),
    CONSTRAINT ck_stipend_extra CHECK (extra_per_session IS NULL OR extra_per_session >= 0)
);
CREATE INDEX IF NOT EXISTS idx_stipend_version_stipend ON t_invigilator_stipend_version (stipend_id);
CREATE INDEX IF NOT EXISTS idx_stipend_version_status ON t_invigilator_stipend_version (status);

-- ============ 聘任记录（一个批次考场/角色槽位一条；换人/签到/缺勤在主表反映当前态，版本留痕） ============
CREATE TABLE IF NOT EXISTS t_invigilator_appointment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- 业务流水号（整条聘任共用，便于按聘任查版本链）
    appointment_no VARCHAR(40) NOT NULL,
    batch_id BIGINT NOT NULL,
    room_id BIGINT,
    -- 槽位类型：ROOM 考场级（监考员） / SITE 考点级（主考/巡考，room_id 可空）
    slot_type VARCHAR(16) NOT NULL DEFAULT 'ROOM',
    role_code VARCHAR(32) NOT NULL,
    -- 当前版本号（最新 APPOINT/REPLACE/CANCEL 版本号）
    current_version_no VARCHAR(40),
    -- 当前被聘监考员（取消槽位置空）
    invigilator_id BIGINT,
    -- 聘任生成方式：AUTO 随排班自动生成 / MANUAL 人事手工补聘
    source VARCHAR(16) NOT NULL DEFAULT 'AUTO',
    -- PENDING 待执行 / CHECKED_IN 已签到（计酬） / ABSENT 缺勤（不计费） / CANCELLED 取消
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    -- 计酬状态：CALCULATED 已计津贴 / NONE 暂不计酬（待签到，或缺勤/取消）
    pay_status VARCHAR(16) NOT NULL DEFAULT 'NONE',
    -- 计酬所用标准版本快照（角色不同标准不同；标准以后调整不改变本场口径）
    stipend_version_id BIGINT,
    stipend_version_no VARCHAR(40),
    -- 单场标准快照金额
    rate_snapshot DECIMAL(10,2),
    extra_snapshot DECIMAL(10,2),
    -- 实测金额：缺勤/取消为 0；签到后 = rate_snapshot + 超场补贴
    amount DECIMAL(10,2) NOT NULL DEFAULT 0,
    -- 该监考员在本批次的计费场次序号（用于超场补贴，签到计酬时按已计费场次重算）
    session_index_in_batch INT,
    -- 已进入的结算单 id（月末出单时回写；结算单锁定后不能直接改聘任金额）
    settled_in_statement_id BIGINT,
    checked_in_at TIMESTAMP,
    checked_in_by VARCHAR(64),
    absent_marked_by VARCHAR(64),
    absent_marked_at TIMESTAMP,
    row_version INT NOT NULL DEFAULT 1,
    operator VARCHAR(64),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    -- 同批次同考场同角色只允许一条"未取消"槽位：CANCELLED 历史行保留，故唯一口径放代码层校验
    -- （重排后考场再次启用时可重新建槽位，旧取消行不拦）
    CONSTRAINT ck_appointment_slot_type CHECK (slot_type IN ('ROOM','SITE')),
    CONSTRAINT ck_appointment_amount CHECK (amount >= 0)
);
CREATE INDEX IF NOT EXISTS idx_appointment_batch ON t_invigilator_appointment (batch_id);
CREATE INDEX IF NOT EXISTS idx_appointment_inv ON t_invigilator_appointment (invigilator_id);
CREATE INDEX IF NOT EXISTS idx_appointment_status ON t_invigilator_appointment (status);
CREATE INDEX IF NOT EXISTS idx_appointment_pay ON t_invigilator_appointment (pay_status);

-- ============ 聘任记录版本（初聘 APPOINT；换人 REPLACE；取消 CANCEL；只追加） ============
CREATE TABLE IF NOT EXISTS t_invigilator_appointment_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id BIGINT NOT NULL,
    appointment_no VARCHAR(40) NOT NULL,
    -- v1 初聘 / v2.. 换人 / 取消
    version_seq INT NOT NULL,
    version_no VARCHAR(40) NOT NULL,
    -- APPOINT 初聘生成 / REPLACE 换人 / CANCEL 取消聘任
    change_type VARCHAR(16) NOT NULL,
    -- 版本对应聘任状态：PENDING / CHECKED_IN / ABSENT / CANCELLED
    status VARCHAR(16) NOT NULL,
    invigilator_id BIGINT,
    -- 换人场景：前任与新任，便于核对
    from_invigilator_id BIGINT,
    to_invigilator_id BIGINT,
    role_code VARCHAR(32) NOT NULL,
    stipend_version_id BIGINT,
    stipend_version_no VARCHAR(40),
    rate_snapshot DECIMAL(10,2),
    extra_snapshot DECIMAL(10,2),
    -- 版本生成时主表计酬状态/金额快照
    pay_status VARCHAR(16),
    amount DECIMAL(10,2),
    reason VARCHAR(255),
    operator VARCHAR(64),
    changed_at TIMESTAMP NOT NULL,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_appointment_version_no UNIQUE (version_no),
    CONSTRAINT ck_app_version_seq CHECK (version_seq >= 1),
    CONSTRAINT ck_app_version_amount CHECK (amount IS NULL OR amount >= 0)
);
CREATE INDEX IF NOT EXISTS idx_appversion_appointment ON t_invigilator_appointment_version (appointment_id);
CREATE INDEX IF NOT EXISTS idx_appversion_invigilator ON t_invigilator_appointment_version (invigilator_id);

-- ============ 场次签到（一个聘任槽位一条；记录到场与异常） ============
CREATE TABLE IF NOT EXISTS t_invigilator_checkin (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id BIGINT NOT NULL,
    batch_id BIGINT NOT NULL,
    room_id BIGINT,
    invigilator_id BIGINT NOT NULL,
    role_code VARCHAR(32) NOT NULL,
