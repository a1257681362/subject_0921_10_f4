-- ============ 结算单（一人一月一条；DRAFT 草稿 / CONFIRMED 已确认锁定） ============
CREATE TABLE IF NOT EXISTS t_invigilator_settlement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    statement_no VARCHAR(40) NOT NULL,
    -- 结算归属月份，格式 yyyyMM（按聘任对应批次考试日期归月）
    period VARCHAR(6) NOT NULL,
    invigilator_id BIGINT NOT NULL,
    staff_no VARCHAR(40) NOT NULL,
    name VARCHAR(64) NOT NULL,
    organization VARCHAR(128),
    -- DRAFT 草稿（可重复出单覆盖）/ CONFIRMED 已确认锁定（要改走调整单）
    status VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
    -- 场次金额合计（聘任计酬汇总，不含调整）
    session_amount DECIMAL(12,2) NOT NULL DEFAULT 0,
    -- 调整金额合计（补发为正、扣减为负）
    adjust_amount DECIMAL(12,2) NOT NULL DEFAULT 0,
    -- 应付合计 = 场次金额 + 调整金额
    total_amount DECIMAL(12,2) NOT NULL DEFAULT 0,
    session_count INT NOT NULL DEFAULT 0,
    adjust_count INT NOT NULL DEFAULT 0,
    generated_by VARCHAR(64),
    generated_at TIMESTAMP,
    confirmed_by VARCHAR(64),
    confirmed_at TIMESTAMP,
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    -- 一人一月一条结算单
    CONSTRAINT uk_settlement_period_inv UNIQUE (period, invigilator_id),
    CONSTRAINT uk_settlement_no UNIQUE (statement_no)
);
CREATE INDEX IF NOT EXISTS idx_settlement_period ON t_invigilator_settlement (period);
CREATE INDEX IF NOT EXISTS idx_settlement_inv ON t_invigilator_settlement (invigilator_id);
CREATE INDEX IF NOT EXISTS idx_settlement_status ON t_invigilator_settlement (status);

-- ============ 结算单明细（一行一场聘任计酬；出单时快照，锁定后不被聘任变动影响） ============
CREATE TABLE IF NOT EXISTS t_invigilator_settlement_item (
