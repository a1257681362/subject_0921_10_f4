    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_invigilator_code UNIQUE (code)
);

-- ============ 监考津贴标准（角色不同标准不同；可按项目/批次时段配置，按生效区间取值并冻结版本号） ============
CREATE TABLE IF NOT EXISTS t_invigilator_allowance_rate (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(32) NOT NULL,
    name VARCHAR(128) NOT NULL,
    -- 适用项目（缺省 DEFAULT 通用）
    project_code VARCHAR(32) NOT NULL DEFAULT 'DEFAULT',
    -- CHIEF 主考 / INVIGILATOR 监考 / PATROL 巡考
    role_code VARCHAR(24) NOT NULL,
    -- 单场津贴（元）
    amount DECIMAL(10,2) NOT NULL,
    -- 生效起止（闭区间）；为空表示长期有效；同一项目+角色同期不允许重叠
    effective_from DATE,
    effective_to DATE,
    status VARCHAR(16) NOT NULL DEFAULT 'ENABLED',
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_allowance_rate_code UNIQUE (code),
    CONSTRAINT ck_allowance_amount CHECK (amount >= 0)
);
CREATE INDEX IF NOT EXISTS idx_rate_role ON t_invigilator_allowance_rate (project_code, role_code);

-- ============ 监考排班（编排之后按场次把监考人员排进考场；聘任随排班生成） ============
CREATE TABLE IF NOT EXISTS t_invigilation_shift (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL,
    room_id BIGINT NOT NULL,
    -- 本场监考角色（不同角色标准不同）
    role_code VARCHAR(24) NOT NULL DEFAULT 'INVIGILATOR',
    -- 排班指定的监考人员；换人后更新为现任，历史在聘任版本/替换记录中保留
    invigilator_id BIGINT NOT NULL,
    -- 场次时间（缺省取批次时间，可单独调整）
    shift_start TIMESTAMP,
    shift_end TIMESTAMP,
    -- SCHEDULED 已排班 / CANCELLED 已取消（场次取消，不计聘任计费）
    status VARCHAR(16) NOT NULL DEFAULT 'SCHEDULED',
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_shift_batch ON t_invigilation_shift (batch_id);
CREATE INDEX IF NOT EXISTS idx_shift_room ON t_invigilation_shift (batch_id, room_id);
CREATE INDEX IF NOT EXISTS idx_shift_invigilator ON t_invigilation_shift (invigilator_id);

-- ============ 聘任记录主表（一个场次一条；金额/状态取当前版本，版本链可追溯） ============
CREATE TABLE IF NOT EXISTS t_appointment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_no VARCHAR(48) NOT NULL,
    batch_id BIGINT NOT NULL,
    room_id BIGINT NOT NULL,
    shift_id BIGINT NOT NULL,
    project_code VARCHAR(32) NOT NULL DEFAULT 'DEFAULT',
    -- 当前在岗监考人员（换人后为接任者；被换下者保留在版本链与替换记录中）
    invigilator_id BIGINT NOT NULL,
    invigilator_code VARCHAR(32) NOT NULL,
    invigilator_name VARCHAR(64) NOT NULL,
    role_code VARCHAR(24) NOT NULL,
    -- 当前版本号（从 1 起，换人/签到/缺勤/取消各追加一版）
    current_version INT NOT NULL DEFAULT 1,
    -- 聘任状态（当前版本状态）：
    -- APPOINTED 已聘任 / REPLACED 已换人 / CHECKED_IN 已签到 / ABSENT 缺勤 / CANCELLED 已取消
    status VARCHAR(24) NOT NULL DEFAULT 'APPOINTED',
    -- 当前版本计津贴口径（在生成/换人时冻结），签到不再改标准
    rate_id BIGINT,
    rate_code VARCHAR(32),
    allowance_amount DECIMAL(10,2) NOT NULL DEFAULT 0,
    -- 计费标记：仅 CHECKED_IN 计费；缺勤/取消/被换下不计费
    billable BOOLEAN NOT NULL DEFAULT FALSE,
    -- 签到钟点（结算周期按签到月归属；换人后由接任者签到位）
    sign_in_at TIMESTAMP,
    -- 是否已进入已确认结算单（锁定后只能走调整）
    settled BOOLEAN NOT NULL DEFAULT FALSE,
    settlement_id BIGINT,
    remark VARCHAR(255),
    operator VARCHAR(64),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_appointment_no UNIQUE (appointment_no),
    CONSTRAINT uk_appointment_shift UNIQUE (shift_id)
);
CREATE INDEX IF NOT EXISTS idx_appointment_batch ON t_appointment (batch_id);
CREATE INDEX IF NOT EXISTS idx_appointment_invigilator ON t_appointment (invigilator_id);
CREATE INDEX IF NOT EXISTS idx_appointment_status ON t_appointment (status);
CREATE INDEX IF NOT EXISTS idx_appointment_billable ON t_appointment (billable);

-- ============ 聘任记录版本（每次生成/换人/签到/缺勤/取消只追加一版，永不修改） ============
CREATE TABLE IF NOT EXISTS t_appointment_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id BIGINT NOT NULL,
    version_no INT NOT NULL,
    -- 本版状态：APPOINTED / REPLACED / CHECKED_IN / ABSENT / CANCELLED
    status VARCHAR(24) NOT NULL,
    -- 本版持聘人（换人版本里：REPLACED 版记被换下者，新版 APPOINTED 记接任者）
    invigilator_id BIGINT NOT NULL,
    invigilator_code VARCHAR(32) NOT NULL,
    invigilator_name VARCHAR(64) NOT NULL,
    role_code VARCHAR(24) NOT NULL,
    -- 本版冻结的津贴口径
    rate_id BIGINT,
    rate_code VARCHAR(32),
    allowance_amount DECIMAL(10,2) NOT NULL DEFAULT 0,
    billable BOOLEAN NOT NULL DEFAULT FALSE,
    -- CREATE 随排班生成 / REPLACE 换人 / CHECKIN 签到 / ABSENT 缺勤 / CANCEL 取消
    change_type VARCHAR(16) NOT NULL,
    change_reason VARCHAR(255),
    -- 关联替换记录（换人版本互相指向同一条替换记录）
    replacement_id BIGINT,
    sign_in_at TIMESTAMP,
    operator VARCHAR(64),
    changed_at TIMESTAMP NOT NULL,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_appointment_version UNIQUE (appointment_id, version_no)
);
CREATE INDEX IF NOT EXISTS idx_appt_version_appt ON t_appointment_version (appointment_id);
CREATE INDEX IF NOT EXISTS idx_appt_version_invigilator ON t_appointment_version (invigilator_id);

-- ============ 换人替换记录（一次换人一条：谁换下谁、谁接任、原因与经办，双向可查） ============
